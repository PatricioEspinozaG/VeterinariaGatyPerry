CREATE TABLE PRODUCTOS (
    CODIGO VARCHAR(12) NOT NULL,
    CATEGORIA VARCHAR(60) NOT NULL,
    NOMBRE VARCHAR(120) NOT NULL,
    PRINCIPIO_ACTIVO VARCHAR(120),
    PRESENTACION VARCHAR(120),
    ESPECIES VARCHAR(80),
    STOCK INTEGER DEFAULT 0 NOT NULL,
    PRECIO BIGINT NOT NULL,
    STOCK_CRITICO INTEGER DEFAULT 5 NOT NULL,
    ACTIVO BOOLEAN DEFAULT TRUE NOT NULL,
    VERSION BIGINT DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PRODUCTOS PRIMARY KEY (CODIGO),
    CONSTRAINT CK_PRODUCTOS_STOCK CHECK (STOCK >= 0),
    CONSTRAINT CK_PRODUCTOS_PRECIO CHECK (PRECIO >= 0),
    CONSTRAINT CK_PRODUCTOS_STOCK_CRITICO CHECK (STOCK_CRITICO >= 0),
    CONSTRAINT CK_PRODUCTOS_ACTIVO CHECK (ACTIVO IN (FALSE, TRUE))
);

CREATE TABLE RESERVAS_STOCK (
    ID_PEDIDO VARCHAR(36) NOT NULL,
    ESTADO VARCHAR(12) DEFAULT 'RESERVADA' NOT NULL,
    CREADA_EN TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_RESERVAS_STOCK PRIMARY KEY (ID_PEDIDO),
    CONSTRAINT CK_RESERVAS_STOCK_ESTADO
        CHECK (ESTADO IN ('RESERVADA', 'CONFIRMADA', 'LIBERADA'))
);

CREATE TABLE RESERVAS_STOCK_ITEMS (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ID_PEDIDO VARCHAR(36) NOT NULL,
    CODIGO_PRODUCTO VARCHAR(12) NOT NULL,
    NOMBRE_PRODUCTO VARCHAR(120) NOT NULL,
    CANTIDAD INTEGER NOT NULL,
    PRECIO_UNITARIO BIGINT NOT NULL,
    CONSTRAINT PK_RESERVAS_STOCK_ITEMS PRIMARY KEY (ID),
    CONSTRAINT UK_RESERVAS_STOCK_PRODUCTO UNIQUE (ID_PEDIDO, CODIGO_PRODUCTO),
    CONSTRAINT FK_RESERVAS_ITEMS_RESERVA
        FOREIGN KEY (ID_PEDIDO) REFERENCES RESERVAS_STOCK (ID_PEDIDO),
    CONSTRAINT FK_RESERVAS_ITEMS_PRODUCTO
        FOREIGN KEY (CODIGO_PRODUCTO) REFERENCES PRODUCTOS (CODIGO),
    CONSTRAINT CK_RESERVAS_ITEMS_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_RESERVAS_ITEMS_PRECIO CHECK (PRECIO_UNITARIO >= 0)
);

CREATE INDEX IDX_PRODUCTOS_CATEGORIA ON PRODUCTOS (CATEGORIA);
CREATE INDEX IDX_RESERVAS_STOCK_ESTADO ON RESERVAS_STOCK (ESTADO);
