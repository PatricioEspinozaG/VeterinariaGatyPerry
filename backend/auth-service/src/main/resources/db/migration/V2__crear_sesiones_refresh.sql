CREATE TABLE SESIONES_REFRESH (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY,
    USUARIO_ID BIGINT NOT NULL,
    FAMILIA_ID UUID NOT NULL,
    TOKEN_HASH VARCHAR(64) NOT NULL,
    CREADO_EN TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    EXPIRA_EN TIMESTAMPTZ NOT NULL,
    USADO_EN TIMESTAMPTZ,
    REVOCADO_EN TIMESTAMPTZ,

    CONSTRAINT PK_SESIONES_REFRESH PRIMARY KEY (ID),
    CONSTRAINT FK_SESIONES_REFRESH_USUARIO
        FOREIGN KEY (USUARIO_ID) REFERENCES USUARIOS (ID)
        ON DELETE CASCADE,
    CONSTRAINT UK_SESIONES_REFRESH_TOKEN_HASH UNIQUE (TOKEN_HASH),
    CONSTRAINT CK_SESIONES_REFRESH_TOKEN_HASH
        CHECK (LENGTH(TOKEN_HASH) = 64),
    CONSTRAINT CK_SESIONES_REFRESH_EXPIRACION
        CHECK (EXPIRA_EN > CREADO_EN)
);

CREATE INDEX IX_SESIONES_REFRESH_USUARIO
    ON SESIONES_REFRESH (USUARIO_ID);

CREATE INDEX IX_SESIONES_REFRESH_FAMILIA
    ON SESIONES_REFRESH (FAMILIA_ID);

CREATE INDEX IX_SESIONES_REFRESH_EXPIRACION
    ON SESIONES_REFRESH (EXPIRA_EN);