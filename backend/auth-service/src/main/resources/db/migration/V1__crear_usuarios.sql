CREATE TABLE USUARIOS (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    RUN VARCHAR2(9 CHAR) NOT NULL,
    NOMBRE VARCHAR2(80 CHAR) NOT NULL,
    APELLIDOS VARCHAR2(100 CHAR) NOT NULL,
    EMAIL VARCHAR2(254 CHAR) NOT NULL,
    TELEFONO VARCHAR2(20 CHAR) NOT NULL,
    PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
    REGION VARCHAR2(80 CHAR) NOT NULL,
    COMUNA VARCHAR2(80 CHAR) NOT NULL,
    DIRECCION VARCHAR2(200 CHAR),
    ROL VARCHAR2(20 CHAR) DEFAULT 'CLIENTE' NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    VERSION NUMBER(19) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_USUARIOS PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIOS_RUN UNIQUE (RUN),
    CONSTRAINT UK_USUARIOS_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIOS_ROL
        CHECK (ROL IN ('ADMIN', 'RECEPCION', 'CLIENTE')),
    CONSTRAINT CK_USUARIOS_ACTIVO
        CHECK (ACTIVO IN (0, 1))
);