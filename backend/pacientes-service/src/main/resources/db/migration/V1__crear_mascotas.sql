CREATE TABLE MASCOTAS (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_ID VARCHAR2(64 CHAR) NOT NULL,
    NOMBRE VARCHAR2(30 CHAR) NOT NULL,
    ESPECIE VARCHAR2(30 CHAR) NOT NULL,
    RAZA VARCHAR2(30 CHAR) NOT NULL,
    EDAD NUMBER(2) NOT NULL,
    SEXO VARCHAR2(10 CHAR),
    NOTAS VARCHAR2(500 CHAR),
    VERSION NUMBER(19) NOT NULL,
    CONSTRAINT PK_MASCOTAS PRIMARY KEY (ID),
    CONSTRAINT CK_MASCOTAS_EDAD CHECK (EDAD BETWEEN 0 AND 30)
);

CREATE INDEX IDX_MASCOTAS_USER_ID ON MASCOTAS (USER_ID);