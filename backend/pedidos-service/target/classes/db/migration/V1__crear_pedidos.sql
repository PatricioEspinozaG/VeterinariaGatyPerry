CREATE TABLE PEDIDOS (
    ID VARCHAR2(36 CHAR) NOT NULL,
    USER_ID NUMBER(19),
    NOMBRE_CLIENTE VARCHAR2(120 CHAR) NOT NULL,
    EMAIL_CLIENTE VARCHAR2(254 CHAR) NOT NULL,
    METODO_ENTREGA VARCHAR2(10 CHAR) NOT NULL,
    REGION VARCHAR2(80 CHAR),
    COMUNA VARCHAR2(80 CHAR),
    DIRECCION VARCHAR2(200 CHAR),
    SUBTOTAL NUMBER(12) NOT NULL,
    ENVIO NUMBER(12) NOT NULL,
    TOTAL NUMBER(12) NOT NULL,
    ESTADO VARCHAR2(20 CHAR) DEFAULT 'REGISTRADO' NOT NULL,
    CREADO_EN TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PEDIDOS PRIMARY KEY (ID),
    CONSTRAINT CK_PEDIDOS_USER_ID CHECK (USER_ID IS NULL OR USER_ID > 0),
    CONSTRAINT CK_PEDIDOS_METODO CHECK (METODO_ENTREGA IN ('envio', 'retiro')),
    CONSTRAINT CK_PEDIDOS_SUBTOTAL CHECK (SUBTOTAL >= 0),
    CONSTRAINT CK_PEDIDOS_ENVIO CHECK (ENVIO >= 0),
    CONSTRAINT CK_PEDIDOS_TOTAL CHECK (TOTAL = SUBTOTAL + ENVIO),
    CONSTRAINT CK_PEDIDOS_ESTADO CHECK (ESTADO IN ('REGISTRADO'))
);

CREATE TABLE PEDIDO_ITEMS (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    PEDIDO_ID VARCHAR2(36 CHAR) NOT NULL,
    CODIGO_PRODUCTO VARCHAR2(12 CHAR) NOT NULL,
    NOMBRE_PRODUCTO VARCHAR2(120 CHAR) NOT NULL,
    CANTIDAD NUMBER(9) NOT NULL,
    PRECIO_UNITARIO NUMBER(12) NOT NULL,
    TOTAL_LINEA NUMBER(12) NOT NULL,
    CONSTRAINT PK_PEDIDO_ITEMS PRIMARY KEY (ID),
    CONSTRAINT FK_PEDIDO_ITEMS_PEDIDO
        FOREIGN KEY (PEDIDO_ID) REFERENCES PEDIDOS (ID),
    CONSTRAINT UK_PEDIDO_ITEMS_PRODUCTO UNIQUE (PEDIDO_ID, CODIGO_PRODUCTO),
    CONSTRAINT CK_PEDIDO_ITEMS_CANTIDAD CHECK (CANTIDAD > 0),
    CONSTRAINT CK_PEDIDO_ITEMS_PRECIO CHECK (PRECIO_UNITARIO >= 0),
    CONSTRAINT CK_PEDIDO_ITEMS_TOTAL CHECK (
        TOTAL_LINEA = CANTIDAD * PRECIO_UNITARIO
    )
);

CREATE INDEX IDX_PEDIDOS_USUARIO_FECHA ON PEDIDOS (USER_ID, CREADO_EN);
CREATE INDEX IDX_PEDIDO_ITEMS_PEDIDO ON PEDIDO_ITEMS (PEDIDO_ID);
