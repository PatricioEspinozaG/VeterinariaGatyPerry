CREATE TABLE CITAS (
    ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    USER_ID NUMBER(19) NOT NULL,
    MASCOTA_ID NUMBER(19) NOT NULL,
    SERVICIO VARCHAR2(80 CHAR) NOT NULL,
    FECHA_HORA TIMESTAMP NOT NULL,
    MOTIVO VARCHAR2(200 CHAR) NOT NULL,
    ESTADO VARCHAR2(20 CHAR) DEFAULT 'PENDIENTE' NOT NULL,
    VERSION NUMBER(19) NOT NULL,
    CONSTRAINT PK_CITAS PRIMARY KEY (ID),
    CONSTRAINT CK_CITAS_USER_ID CHECK (USER_ID > 0),
    CONSTRAINT CK_CITAS_MASCOTA_ID CHECK (MASCOTA_ID > 0),
    CONSTRAINT CK_CITAS_ESTADO CHECK (
        ESTADO IN ('PENDIENTE', 'CONFIRMADA', 'COMPLETADA', 'CANCELADA')
    )
);

CREATE INDEX IDX_CITAS_USUARIO_FECHA ON CITAS (USER_ID, FECHA_HORA);
CREATE INDEX IDX_CITAS_FECHA ON CITAS (FECHA_HORA);