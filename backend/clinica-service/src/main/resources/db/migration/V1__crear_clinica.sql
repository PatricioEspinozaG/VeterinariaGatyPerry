CREATE TABLE atenciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mascota_id BIGINT NOT NULL,
    cita_id BIGINT,
    fecha_atencion TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    motivo VARCHAR(200) NOT NULL,
    diagnostico VARCHAR(2000) NOT NULL,
    tratamiento VARCHAR(2000),
    observaciones VARCHAR(4000),
    profesional_responsable VARCHAR(120) NOT NULL,
    registrado_por BIGINT NOT NULL,
    actualizado_por BIGINT NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    motivo_anulacion VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_atenciones_estado
        CHECK (estado IN ('ACTIVA', 'ANULADA')),
    CONSTRAINT ck_atenciones_anulacion
        CHECK (
            (estado = 'ACTIVA' AND motivo_anulacion IS NULL)
            OR (estado = 'ANULADA' AND motivo_anulacion IS NOT NULL)
        )
);

CREATE INDEX idx_atenciones_mascota_fecha
    ON atenciones (mascota_id, fecha_atencion DESC);
CREATE INDEX idx_atenciones_cita
    ON atenciones (cita_id);

CREATE TABLE vacunas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mascota_id BIGINT NOT NULL,
    atencion_id BIGINT,
    nombre_vacuna VARCHAR(160) NOT NULL,
    fecha_aplicacion DATE NOT NULL,
    profesional_responsable VARCHAR(120) NOT NULL,
    lote VARCHAR(120),
    observaciones VARCHAR(2000),
    proxima_dosis DATE,
    registrado_por BIGINT NOT NULL,
    actualizado_por BIGINT NOT NULL,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    estado VARCHAR(20) NOT NULL,
    motivo_anulacion VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT ck_vacunas_estado
        CHECK (estado IN ('ACTIVA', 'ANULADA')),
    CONSTRAINT ck_vacunas_anulacion
        CHECK (
            (estado = 'ACTIVA' AND motivo_anulacion IS NULL)
            OR (estado = 'ANULADA' AND motivo_anulacion IS NOT NULL)
        ),
    CONSTRAINT ck_vacunas_proxima_dosis
        CHECK (proxima_dosis IS NULL OR proxima_dosis > fecha_aplicacion)
);

CREATE INDEX idx_vacunas_mascota_fecha
    ON vacunas (mascota_id, fecha_aplicacion DESC);
CREATE INDEX idx_vacunas_atencion
    ON vacunas (atencion_id);
